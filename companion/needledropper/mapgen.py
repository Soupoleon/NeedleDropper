"""Generate the addon's ``Map.lua`` + ``Map.json`` from packs, and resolve events.

``Map.lua`` (docs/SPEC.md 3.2) is plain Lua 5.1 data assigned to the global
``NeedleDropper_Map``; ``Map.json`` is the same content as JSON. The companion
reads the sidecar to turn an event's ``(hash, n)`` back into a drop. Every map
ever generated is also kept as ``<app_dir>\\maps\\<hash>.json`` so events from
an addon still running an older map (no ``/reload`` yet) still resolve.
"""
from __future__ import annotations

import json
import logging
import math
import os
import re
import threading
import time
from dataclasses import dataclass, replace
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Iterable, Optional, Sequence

from . import __version__, protocol
from .config import atomic_write_text
from .models import TEST_DROP, Drop, Event, Flags

MAP_VERSION = 1
LUA_GLOBAL = "NeedleDropper_Map"

_LUA_KEYWORDS = {
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local",
    "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
}
_IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

log = logging.getLogger("needledropper.mapgen")


class MapError(ValueError):
    """A Map.json file is missing, unreadable or malformed."""


# ----------------------------------------------------------------- build ----

def utc_now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def build_map(drops: Sequence[Drop], pack_names: Sequence[str] = (), *, generated: Optional[str] = None) -> dict:
    """The canonical map dict ``{version, hash, generated, packs, drops}``.

    ``drops`` must already be numbered (see ``packs.assign_numbers``).
    """
    ordered = sorted(drops, key=lambda d: d.n)
    seen_n: set[int] = set()
    seen_id: set[str] = set()
    for d in ordered:
        if not 1 <= int(d.n) <= 0xFFFF:
            raise ValueError(f"drop {d.id!r} has n={d.n}; numbers must be 1..65535 (use packs.assign_numbers)")
        if d.n in seen_n:
            raise ValueError(f"duplicate drop number n={d.n}")
        if d.id in seen_id:
            raise ValueError(f"duplicate drop id {d.id!r}")
        seen_n.add(d.n)
        seen_id.add(d.id)
    entries = [d.to_map_entry() for d in ordered]
    return {
        "version": MAP_VERSION,
        "hash": protocol.map_hash(entries),
        "generated": generated or utc_now_iso(),
        "packs": [str(p) for p in pack_names],
        "drops": entries,
    }


# ------------------------------------------------------------------- Lua ----

def lua_string(s: str) -> str:
    """A double-quoted Lua 5.1 string literal (UTF-8 kept as-is, controls escaped)."""
    out = ['"']
    for ch in str(s):
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 32 or o == 127:
            out.append(f"\\{o:03d}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def _lua_key(k: str) -> str:
    return k if _IDENT_RE.match(k) and k not in _LUA_KEYWORDS else f"[{lua_string(k)}]"


def lua_value(v: Any) -> str:
    """Render a JSON-like value as a single-line Lua constructor/literal."""
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if not math.isfinite(v):
            raise ValueError(f"cannot write non-finite number {v!r} to Lua")
        return repr(v)
    if isinstance(v, str):
        return lua_string(v)
    if isinstance(v, dict):
        parts = [f"{_lua_key(str(k))} = {lua_value(x)}" for k, x in v.items() if x is not None]
        return "{ " + ", ".join(parts) + " }" if parts else "{}"
    if isinstance(v, (list, tuple)):
        parts = [lua_value(x) for x in v]
        return "{ " + ", ".join(parts) + " }" if parts else "{}"
    raise TypeError(f"cannot write {type(v).__name__} to Lua")


def _comment_safe(s: str) -> str:
    return re.sub(r"[\r\n]+", " ", str(s))


def render_map_lua(map_data: dict) -> str:
    """Map.lua source text for a map dict from :func:`build_map`."""
    lines = [
        f"-- Generated by NeedleDropper companion {_comment_safe(__version__)} at "
        f"{_comment_safe(map_data['generated'])}. Edit packs, not this file.",
        f"-- {len(map_data['drops'])} drop(s) from: {_comment_safe(', '.join(map_data['packs'])) or '(no packs)'}",
        f"{LUA_GLOBAL} = {{",
        f"  version = {int(map_data['version'])},",
        f"  hash = {int(map_data['hash'])},",
        f"  generated = {lua_string(map_data['generated'])},",
        f"  packs = {lua_value(list(map_data['packs']))},",
        "  drops = {",
    ]
    for entry in map_data["drops"]:
        lines.append(f"    {lua_value(entry)},")
    lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_map_json(map_data: dict) -> str:
    return json.dumps(map_data, indent=2, ensure_ascii=False) + "\n"


# ----------------------------------------------------------------- write ----

@dataclass
class MapWriteResult:
    hash: int
    lua_path: Path
    json_path: Path
    registry_path: Optional[Path]
    drop_count: int


def write_map(map_data: dict, out_dir: str | os.PathLike[str], *,
              maps_dir: Optional[str | os.PathLike[str]] = None) -> MapWriteResult:
    """Atomically write ``Map.lua`` + ``Map.json`` into ``out_dir`` and (optionally)
    ``<maps_dir>\\<hash>.json``. Map.json is written before Map.lua so the
    companion can always resolve whatever the addon loads next.
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    js = render_map_json(map_data)
    reg_path: Optional[Path] = None
    if maps_dir is not None:
        reg_path = Path(maps_dir) / f"{int(map_data['hash'])}.json"
        atomic_write_text(reg_path, js)
    json_path = atomic_write_text(out / "Map.json", js)
    lua_path = atomic_write_text(out / "Map.lua", render_map_lua(map_data))
    return MapWriteResult(int(map_data["hash"]), lua_path, json_path, reg_path, len(map_data["drops"]))


def load_map_json(path: str | os.PathLike[str]) -> dict:
    """Read and sanity-check a Map.json / maps\\<hash>.json file."""
    p = Path(path)
    try:
        data = json.loads(p.read_text(encoding="utf-8-sig"))
    except FileNotFoundError as exc:
        raise MapError(f"{p}: not found") from exc
    except (OSError, json.JSONDecodeError) as exc:
        raise MapError(f"{p}: unreadable map: {exc}") from exc
    if not isinstance(data, dict) or not isinstance(data.get("drops"), list):
        raise MapError(f"{p}: not a NeedleDropper map (expected an object with \"drops\")")
    h = data.get("hash")
    if not isinstance(h, int) or isinstance(h, bool) or not 0 <= h <= 0xFFFF:
        raise MapError(f"{p}: missing or invalid \"hash\"")
    for i, d in enumerate(data["drops"]):
        if not isinstance(d, dict) or not isinstance(d.get("n"), int) or not isinstance(d.get("id"), str):
            raise MapError(f"{p}: drops[{i}] lacks n/id")
    data.setdefault("packs", [])
    data.setdefault("version", MAP_VERSION)
    return data


# -------------------------------------------------------------- registry ----

PACK_ONLY_FIELDS = ("spotify", "youtube", "appleMusic", "file", "volume")


def _same_song(a: Drop, b: Drop) -> bool:
    def k(s: str) -> str:
        return " ".join((s or "").casefold().split())
    return k(a.title) == k(b.title) and k(a.artist) == k(b.artist)


class MapRegistry:
    """Resolves ``(hash, n)`` from events to :class:`Drop` objects.

    Lookup order for a hash: the installed addon's ``Map.json`` (if its hash
    matches), then ``<app_dir>\\maps\\<hash>.json``, then the map the current
    packs would generate. The resolved drop is enriched with pack-only fields
    (spotify/youtube/appleMusic/file/volume, art) from the current packs by
    drop id -- as long as the pack still has the same song for that id.

    Thread-safe.
    """

    def __init__(self, paths: Any, pack_drops: Optional[Iterable[Drop]] = None, *,
                 pack_loader: Optional[Callable[[], Optional[list[Drop]]]] = None,
                 test_drop: Optional[Drop] = None, logger: Optional[logging.Logger] = None,
                 refresh_interval: float = 2.0) -> None:
        self.paths = paths
        self.log = logger or log
        self._lock = threading.RLock()
        self._pack_loader = pack_loader
        self._refresh_interval = refresh_interval
        self._last_refresh = 0.0
        self._pack_by_id: dict[str, Drop] = {}
        self._pack_map: Optional[dict] = None
        self._file_cache: dict[str, tuple[tuple[int, int], dict]] = {}
        self.test_drop = test_drop or TEST_DROP
        if pack_drops is not None:
            self.set_pack_drops(pack_drops)
        elif pack_loader is not None:
            self.refresh(force=True)

    # ---- packs
    def set_pack_drops(self, drops: Iterable[Drop]) -> None:
        with self._lock:
            lst = list(drops)
            self._pack_by_id = {d.id: d for d in lst}
            try:
                self._pack_map = build_map(lst, generated="-") if lst else None
            except ValueError:
                self._pack_map = None

    @property
    def pack_drops(self) -> list[Drop]:
        with self._lock:
            return sorted(self._pack_by_id.values(), key=lambda d: (d.n, d.id))

    @property
    def pack_hash(self) -> Optional[int]:
        with self._lock:
            return self._pack_map["hash"] if self._pack_map else None

    def refresh(self, force: bool = False) -> None:
        """Re-run the pack loader (rate-limited) so edits/resolutions show up live."""
        if self._pack_loader is None:
            return
        now = time.monotonic()
        if not force and now - self._last_refresh < self._refresh_interval:
            return
        self._last_refresh = now
        try:
            drops = self._pack_loader()
        except Exception as exc:  # loader is user-data driven; never break resolution
            self.log.warning("could not reload packs: %s", exc)
            return
        if drops is not None:
            self.set_pack_drops(drops)

    # ---- maps
    def _load_cached(self, path: Path) -> Optional[dict]:
        try:
            st = path.stat()
        except OSError:
            return None
        key = (st.st_mtime_ns, st.st_size)
        with self._lock:
            hit = self._file_cache.get(str(path))
            if hit and hit[0] == key:
                return hit[1]
        try:
            data = load_map_json(path)
        except MapError as exc:
            self.log.warning("%s", exc)
            return None
        with self._lock:
            self._file_cache[str(path)] = (key, data)
        return data

    def installed_map(self) -> Optional[dict]:
        return self._load_cached(Path(self.paths.addon_dir) / "Map.json")

    @property
    def installed_hash(self) -> Optional[int]:
        m = self.installed_map()
        return m["hash"] if m else None

    def map_for_hash(self, h: int) -> Optional[dict]:
        m = self.installed_map()
        if m is not None and m["hash"] == h:
            return m
        maps_dir = getattr(self.paths, "maps_dir", None)
        if maps_dir is not None:
            m = self._load_cached(Path(maps_dir) / f"{int(h)}.json")
            if m is not None and m["hash"] == h:
                return m
        with self._lock:
            if self._pack_map is not None and self._pack_map["hash"] == h:
                return self._pack_map
        return None

    def known_hashes(self) -> list[int]:
        out: set[int] = set()
        m = self.installed_map()
        if m:
            out.add(m["hash"])
        maps_dir = getattr(self.paths, "maps_dir", None)
        if maps_dir is not None and Path(maps_dir).is_dir():
            for p in Path(maps_dir).glob("*.json"):
                if p.stem.isdigit():
                    out.add(int(p.stem))
        if self.pack_hash is not None:
            out.add(self.pack_hash)
        return sorted(out)

    # ---- resolution
    def enrich(self, drop: Drop) -> Drop:
        """Attach pack-only fields from the current packs (same id and same song)."""
        with self._lock:
            src = self._pack_by_id.get(drop.id)
        if src is None:
            return drop
        if not _same_song(drop, src):
            self.log.info("drop %s: pack now has %s - %s but the addon's map says %s - %s; "
                          "run build-map and /reload to update the game", drop.id, src.artist, src.title,
                          drop.artist, drop.title)
            return drop
        changes: dict[str, Any] = {}
        for f in PACK_ONLY_FIELDS:
            if getattr(drop, f) in (None, "") and getattr(src, f) not in (None, ""):
                changes[f] = getattr(src, f)
        if not drop.note and src.note:
            changes["note"] = src.note
        if not drop.pack and src.pack:
            changes["pack"] = src.pack
        if src.extra:
            changes["extra"] = {**src.extra, **drop.extra}
        if not drop.durationMs and src.durationMs:
            changes["durationMs"] = src.durationMs
        return replace(drop, **changes) if changes else drop

    def resolve(self, h: int, n: int) -> Optional[Drop]:
        """Drop number ``n`` of the map with hash ``h`` (enriched), or None."""
        self.refresh()
        if n == 0:
            return None
        m = self.map_for_hash(h)
        if m is None:
            return None
        for entry in m["drops"]:
            if entry.get("n") == n:
                return self.enrich(Drop.from_dict(entry))
        return None

    def by_id(self, drop_id: str) -> Optional[Drop]:
        """Current pack drop by id (exact, or matching the chat-sanitized id)."""
        if not drop_id:
            return None
        self.refresh()
        if drop_id == "test":
            return self.test_drop
        with self._lock:
            d = self._pack_by_id.get(drop_id)
            if d is not None:
                return d
            for cand in self._pack_by_id.values():
                if protocol.sanitize_id(cand.id) == drop_id:
                    return cand
        return None

    def resolve_event(self, ev: Event) -> Optional[Drop]:
        """Resolve an event to a drop: test drop for ``n=0``, else ``(hash, n)``,
        falling back to the chat channel's drop id."""
        if ev.n == 0:
            if ev.has(Flags.TEST) or ev.id in ("", "test", "-"):
                return self.test_drop
            return None
        d = self.resolve(ev.hash, ev.n)
        if d is not None:
            return d
        if ev.id:
            d = self.by_id(ev.id)
            if d is not None:
                return d
        return None

    def find(self, query: str) -> Optional[Drop]:
        """Find a pack drop by id or zone/landmark name (``test`` -> test drop)."""
        from .packs import find_drop

        if query.strip().lower() == "test":
            return self.test_drop
        self.refresh()
        return find_drop(self.pack_drops, query)

    def describe_miss(self, ev: Event) -> str:
        """User-facing explanation for an event we could not resolve."""
        inst = self.installed_hash
        if self.map_for_hash(ev.hash) is None:
            hint = f"installed Map.json has hash {inst}" if inst is not None else "no Map.json is installed"
            return (f"unknown map hash {ev.hash} (addon) -- {hint}; run `needledropper build-map` "
                    "and type /reload in game")
        return f"map {ev.hash} has no drop n={ev.n}"

    @classmethod
    def from_config(cls, cfg: dict, paths: Any, *, test_drop: Optional[Drop] = None,
                    logger: Optional[logging.Logger] = None) -> "MapRegistry":
        """A registry whose pack drops reload when pack files or the resolution cache change."""
        from .config import pack_paths_from_config
        from .packs import load_packs_detailed

        state: dict[str, Any] = {"sig": None}
        lg = logger or log

        def signature() -> tuple:
            files = list(pack_paths_from_config(cfg)) + [Path(paths.resolved_cache)]
            sig = []
            for f in files:
                try:
                    st = f.stat()
                    sig.append((str(f), st.st_mtime_ns, st.st_size))
                except OSError:
                    sig.append((str(f), None, None))
            return tuple(sig)

        def loader() -> Optional[list[Drop]]:
            sig = signature()
            if sig == state["sig"]:
                return None
            state["sig"] = sig
            ps = load_packs_detailed(pack_paths_from_config(cfg), resolved_cache=paths.resolved_cache)
            for issue in ps.errors:
                lg.warning("%s", issue)
            return ps.drops

        return cls(paths, pack_loader=loader, test_drop=test_drop, logger=logger)


def configured_test_drop(cfg: dict) -> Drop:
    """The ``test`` drop (n=0); optional config key ``testDrop`` gives it a real track."""
    td = cfg.get("testDrop")
    if not isinstance(td, dict):
        return TEST_DROP
    from .packs import normalize_spotify, normalize_youtube

    kw: dict[str, Any] = {}
    for k in ("title", "artist", "label", "file", "appleMusic"):
        if isinstance(td.get(k), str) and td[k].strip():
            kw[k] = td[k].strip()
    if isinstance(td.get("spotify"), str):
        kw["spotify"] = normalize_spotify(td["spotify"]) or None
    if isinstance(td.get("youtube"), str):
        kw["youtube"] = normalize_youtube(td["youtube"]) or None
    for k in ("startMs", "durationMs", "volume"):
        if isinstance(td.get(k), int) and not isinstance(td.get(k), bool):
            kw[k] = td[k]
    return replace(TEST_DROP, **kw)
